import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

// 海克斯大乱斗（KIWI）与斗魂竞技场（Cherry）共用同一份强化字典；
// zh_cn 版本自带中文名，供战绩详情悬浮展示。
export const AUGMENTS_URL =
    'https://raw.communitydragon.org/latest/plugins/rcp-be-lol-game-data/global/zh_cn/v1/cherry-augments.json'

const ICON_PATH_PREFIX = '/lol-game-data/assets'

// 输出紧凑结构 { n: 中文名, i: 图标路径, r: 稀有度 }，图标路径去掉 /lol-game-data/assets 前缀，
// 与 buildRuntimeRiotAssetUrl 的 /riot 代理前缀保持一致。
export function buildAugmentDict(augments) {
    return Object.fromEntries(
        augments
            .filter(
                (augment) =>
                    Number.isInteger(augment?.id) &&
                    typeof augment.augmentSmallIconPath === 'string' &&
                    augment.augmentSmallIconPath.startsWith(ICON_PATH_PREFIX),
            )
            .map((augment) => [
                String(augment.id),
                {
                    n: augment.nameTRA || augment.augmentNameId || '',
                    i: augment.augmentSmallIconPath.slice(ICON_PATH_PREFIX.length),
                    r: augment.rarity || '',
                },
            ])
            .sort((a, b) => Number(a[0]) - Number(b[0])),
    )
}

async function loadAugments(inputPath) {
    if (inputPath) {
        return JSON.parse(await readFile(resolve(inputPath), 'utf8'))
    }
    const response = await fetch(AUGMENTS_URL)
    if (!response.ok) {
        throw new Error(`Failed to fetch ${AUGMENTS_URL}: ${response.status} ${response.statusText}`)
    }
    return response.json()
}

async function main() {
    // Optional positional argument: path to a local cherry-augments.json snapshot instead of fetching.
    const inputPath = process.argv[2]
    const augments = await loadAugments(inputPath)
    const dict = buildAugmentDict(augments)
    const output = `// Generated by frontend/scripts/generate-augment-dict.mjs from ${inputPath || AUGMENTS_URL}
// Rerun the script after a game patch adds, renames or retires augments, then commit the regenerated file.
export default ${JSON.stringify(dict, null, 4)}
`
    const scriptDir = dirname(fileURLToPath(import.meta.url))
    const outputPath = resolve(scriptDir, '../src/model/dicts/augments.generated.js')
    await writeFile(outputPath, output, 'utf8')
    console.log(`Generated ${outputPath} with ${Object.keys(dict).length} augments.`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    await main()
}