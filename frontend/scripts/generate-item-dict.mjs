import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

export const ITEMS_URL =
    'https://raw.communitydragon.org/latest/plugins/rcp-be-lol-game-data/global/default/v1/items.json'

const ICON_PATH_PREFIX = '/lol-game-data/assets/ASSETS/Items/Icons2D/'

// Keep every item whose icon lives under the canonical Icons2D folder, including regular,
// mode-specific and Ornn-upgraded variants, so all match records stay renderable.
export function buildItemDict(items) {
    return Object.fromEntries(
        items
            .filter(
                (item) =>
                    Number.isInteger(item?.id) &&
                    typeof item.iconPath === 'string' &&
                    item.iconPath.startsWith(ICON_PATH_PREFIX),
            )
            .map((item) => [String(item.id), item.iconPath.slice(ICON_PATH_PREFIX.length)])
            .sort((a, b) => Number(a[0]) - Number(b[0])),
    )
}

async function loadItems(inputPath) {
    if (inputPath) {
        return JSON.parse(await readFile(resolve(inputPath), 'utf8'))
    }
    const response = await fetch(ITEMS_URL)
    if (!response.ok) {
        throw new Error(`Failed to fetch ${ITEMS_URL}: ${response.status} ${response.statusText}`)
    }
    return response.json()
}

async function main() {
    // Optional positional argument: path to a local items.json snapshot instead of fetching.
    const inputPath = process.argv[2]
    const items = await loadItems(inputPath)
    const dict = buildItemDict(items)
    const output = `// Generated by frontend/scripts/generate-item-dict.mjs from ${inputPath || ITEMS_URL}
// Rerun the script after a game patch adds or renames items, then commit the regenerated file.
export default ${JSON.stringify(dict, null, 4)}
`
    const scriptDir = dirname(fileURLToPath(import.meta.url))
    const outputPath = resolve(scriptDir, '../src/model/dicts/items.generated.js')
    await writeFile(outputPath, output, 'utf8')
    console.log(`Generated ${outputPath} with ${Object.keys(dict).length} items.`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    await main()
}