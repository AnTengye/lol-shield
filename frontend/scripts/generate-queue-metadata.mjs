import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const QUEUES_URL = 'https://static.developer.riotgames.com/docs/lol/queues.json'

const NAME_OVERRIDES = {
    0: '自定义',
    400: '征召匹配',
    420: '单双排',
    430: '自选匹配',
    440: '灵活组排',
    450: '极地大乱斗',
    480: '迅捷模式',
    490: '快速匹配',
    700: '召唤师峡谷 Clash',
    720: '极地大乱斗 Clash',
    830: '人机入门',
    840: '人机新手',
    850: '人机一般',
    870: '人机入门',
    880: '人机新手',
    890: '人机一般',
    900: '无限乱斗',
    1020: '克隆大作战',
    1300: '极限闪击',
    1400: '终极魔典',
    1700: '斗魂竞技场',
    1710: '斗魂竞技场',
    1810: '无尽狂潮单人',
    1820: '无尽狂潮双人',
    1830: '无尽狂潮三人',
    1840: '无尽狂潮四人',
    1900: '无限火力',
    2300: '大乱斗',
    2400: '海克斯大乱斗',
}

function fallbackName(queue) {
    return queue.description || queue.map || `队列 ${queue.queueId}`
}

function isAramLike(queue) {
    return queue.map === 'Howling Abyss' || /ARAM|Howling Abyss/i.test(`${queue.description || ''} ${queue.map || ''}`)
}

const response = await fetch(QUEUES_URL)
if (!response.ok) {
    throw new Error(`Failed to fetch ${QUEUES_URL}: ${response.status} ${response.statusText}`)
}

const queues = await response.json()
const metadata = Object.fromEntries(
    queues.map((queue) => [
        String(queue.queueId),
        {
            name: NAME_OVERRIDES[queue.queueId] || fallbackName(queue),
            map: queue.map || '',
            description: queue.description || '',
            notes: queue.notes || '',
            aramLike: isAramLike(queue),
        },
    ]),
)

const output = `// Generated by frontend/scripts/generate-queue-metadata.mjs from ${QUEUES_URL}
// Keep Chinese names in NAME_OVERRIDES, then rerun the script when Riot adds queues.
export default ${JSON.stringify(metadata, null, 4)}
`

const scriptDir = dirname(fileURLToPath(import.meta.url))
const outputPath = resolve(scriptDir, '../src/model/dicts/queues.generated.js')
await writeFile(outputPath, output, 'utf8')
console.log(`Generated ${outputPath} with ${queues.length} queues.`)
